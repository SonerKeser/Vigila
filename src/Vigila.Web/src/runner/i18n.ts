export const dictionaries: Record<ParticipantLanguage, Dict> = { tr, en };
export type RunnerText = Dict;

export function keyName(code: string, lang: ParticipantLanguage): string {
  if (code === "Space") return lang === "tr" ? "Boşluk" : "Space";
  if (code.startsWith("Key")) return code.slice(3);
  if (code.startsWith("Digit")) return code.slice(5);
  return code;
}

export function durationText(ms: number, lang: ParticipantLanguage): string {
  const min = Math.round(ms / 60000);
  if (lang === "en") return min >= 1 ? `${min} minute${min === 1 ? "" : "s"}` : `${Math.round(ms / 1000)} seconds`;
  return min >= 1 ? `${min} dakika` : `${Math.round(ms / 1000)} saniye`;
}
